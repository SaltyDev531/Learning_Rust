fn main() {
    // FLOATING POINT TYPES
    let x = 2.0;
    let y: f32 = 3.0;

    // NUMERIC OPERATIONS
    let sum = 5 + 10;
    let difference = 95.5 - 4.3;
    let product = 4 * 30;
    let quotient = 56.7 / 32.2;
    let truncated = -5 / 3;
    let remainder = 43 % 5;

    // THE BOOLEAN TYPE
    let t = true;
    let f: bool = false;

    // THE CHARACTER TYPE
    let c = 'z';
    let z: char = 'Z';
    let heart_eyed_cat = '😻';

    // COMPOUND TYPES

    // THE TUPLE TYPE
    let tup = (500, 6.4, 1);
    let (x, y, z) = tup;
    println!("The value of y is: {y}");

    // THE ARRAY TYPE
    let a = [1, 2, 3, 4, 5];

    let first = a[0];
    let second = a[1];
}
